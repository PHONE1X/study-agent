#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Отсев выдуманных пунктов конспекта.

ЗАЧЕМ

Модель уверенно пишет пункты, которых во фрагменте нет. Самый показательный
случай -- в двух заметках подряд появился пункт «Объём корпуса — 3.8 литра»
на стриме по Elden Ring. Этой строки не было ни в транскрипте сессии, ни в
одном окне, которое уходило в модель: она была В САМОЙ ИНСТРУКЦИИ, как пример
формулировки («не "он весит 3.8 литра", а "объём корпуса — 3.8 литра"»).
Модель скопировала пример из промпта в ответ и выдала за факт.

Промпт поправлен, но одного промпта мало: пункт, слов которого во фрагменте
нет, -- это выдумка независимо от того, откуда модель его взяла. Поэтому
здесь стоит детерминированная проверка, а не ещё одна просьба к модели.

КАК

Пункт выбрасывается, если:
  * доля его значимых слов, встречающихся во фрагменте, ниже порога, ЛИБО
  * в нём есть число, которого во фрагменте нет.

Сравнение по первым 5 буквам слова: русский язык склоняет всё подряд, а
полноценная лемматизация тянет за собой зависимости, которых на машине нет.
«осколок» и «осколка» дают одну основу «оскол», этого достаточно.

Порог намеренно мягкий: задача -- ловить выдумку, а не наказывать за
пересказ своими словами. Всё выброшенное печатается в stderr, чтобы было
видно, что именно отсеялось.

ИСПОЛЬЗОВАНИЕ
    ground_bullets.py <файл-с-фрагментом> < пункты > отфильтрованные-пункты
"""

import re
import sys

THRESHOLD = 0.40   # ниже этой доли знакомых слов пункт считается выдуманным
TRUST_SHARE = 0.65 # выше этой доли пункту прощается незнакомое число
DUP_SHARE  = 0.55  # выше этой схожести слов пункт считается повтором
STEM = 5           # сколько первых букв берём за основу слова
MIN_WORD = 4       # слова короче не несут смысла для сверки
MIN_CONTENT = 2    # пункт с одним значимым словом не проверяем -- не на чем
NUM_NOISE_WORDS = 6  # столько значимых слов должно быть рядом с россыпью чисел

# Слова, которые есть в любом тексте и ничего не подтверждают.
STOP = {
    "быть", "было", "были", "если", "когда", "чтобы", "потому", "поэтому",
    "также", "очень", "можно", "нужно", "нужен", "нужна", "надо", "этот",
    "эта", "это", "того", "тому", "тем", "который", "которые", "которая",
    "после", "перед", "через", "между", "более", "менее", "самый", "самое",
    "всего", "всех", "весь", "вся", "себя", "свой", "своя", "свои", "там",
    "здесь", "тогда", "затем", "далее", "просто", "только", "может", "могут",
    "будет", "будут", "дает", "даёт", "делает", "делают", "происходит",
}

# Числительные словами. В речи «две с половиной секунды», а в конспекте
# «2.5 секунды» -- без этой таблицы правильный пункт выглядел бы выдуманным.
NUMERALS = {
    "ноль": 0, "один": 1, "одна": 1, "одно": 1, "два": 2, "две": 2,
    "три": 3, "четыре": 4, "пять": 5, "шесть": 6, "семь": 7, "восемь": 8,
    "девять": 9, "десять": 10, "одиннадцать": 11, "двенадцать": 12,
    "тринадцать": 13, "четырнадцать": 14, "пятнадцать": 15,
    "шестнадцать": 16, "семнадцать": 17, "восемнадцать": 18,
    "девятнадцать": 19, "двадцать": 20, "тридцать": 30, "сорок": 40,
    "пятьдесят": 50, "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80,
    "девяносто": 90, "сто": 100, "двести": 200, "триста": 300,
    "тысяча": 1000, "тысяч": 1000, "тысячи": 1000,
}

_word = re.compile(r"[а-яёa-z]+", re.IGNORECASE)
_num = re.compile(r"\d+(?:[.,]\d+)?")


def stems(text):
    out = set()
    for w in _word.findall(text.lower()):
        if len(w) < MIN_WORD or w in STOP:
            continue
        out.add(w[:STEM])
    return out


def numbers(text):
    return {n.replace(",", ".") for n in _num.findall(text)}


def spoken_numbers(text):
    """Числа, произнесённые словами, в виде цифр: «две с половиной» -> 2, 2.5."""
    words = _word.findall(text.lower())
    out = set()
    for i, w in enumerate(words):
        val = NUMERALS.get(w)
        if val is None:
            continue
        out.add(str(val))
        out.add("%g" % val)
        # «два с половиной», «полтора»
        if words[i + 1:i + 3] == ["с", "половиной"]:
            out.add("%g" % (val + 0.5))
    if "полтора" in words or "полторы" in words:
        out.add("1.5")
    return out


def main():
    if len(sys.argv) < 2:
        # Без фрагмента сверять не с чем -- пропускаем всё как есть.
        sys.stdout.write(sys.stdin.read())
        return
    try:
        with open(sys.argv[1], encoding="utf-8") as f:
            fragment = f.read()
    except OSError:
        sys.stdout.write(sys.stdin.read())
        return

    src_stems = stems(fragment)
    src_nums = numbers(fragment) | spoken_numbers(fragment)
    if not src_stems:
        sys.stdout.write(sys.stdin.read())
        return

    kept, dropped, kept_stems = [], [], []
    for line in sys.stdin.read().splitlines():
        if not line.strip().startswith("-"):
            kept.append(line)
            continue

        body = line.lstrip("- ").strip()
        bs = stems(body)

        # Мусор из чата прямого эфира выглядит как россыпь чисел с парой слов
        # между ними («162, Саня. 162? Уже три варианта. 162, 169, 164»).
        # Формально такой пункт опирается на фрагмент -- слова-то оттуда, --
        # поэтому проверка по словам его пропускает, и ловить приходится по
        # форме: много чисел и почти нет содержания.
        nums = numbers(body)
        if len(nums) >= 3 and len(bs) < NUM_NOISE_WORDS:
            dropped.append((line, "похоже на числа из чата, а не на содержание"))
            continue

        if len(bs) < MIN_CONTENT:
            kept.append(line)
            continue

        share = len(bs & src_stems) / float(len(bs))
        if share < THRESHOLD:
            dropped.append((line, "во фрагменте нет %d%% слов" % int(100 * (1 - share))))
            continue

        # Чужое число -- подозрительно, но только если и остальной пункт плохо
        # опирается на фрагмент. В хорошо привязанном пункте число скорее всего
        # пересчитано из речи («минуты» в «секунды»), а не выдумано.
        bad_num = numbers(body) - src_nums
        if bad_num and share < TRUST_SHARE:
            dropped.append((line, "число не из фрагмента: " + ", ".join(sorted(bad_num))))
            continue

        # Модель охотно пересказывает одну мысль по четыре раза подряд
        # («кунаи подбираются», «кунаи используются», «кунаи кидаются»).
        # Просьба «не повторяйся» в промпте на это не действует, поэтому
        # повторы режутся здесь: пункт, почти совпадающий по словам с уже
        # оставленным, в заметки не идёт.
        dup = False
        for prev in kept_stems:
            union = bs | prev
            if union and len(bs & prev) / float(len(union)) >= DUP_SHARE:
                dup = True
                break
        if dup:
            dropped.append((line, "повтор предыдущего пункта"))
            continue

        kept_stems.append(bs)
        kept.append(line)

    for line, why in dropped:
        print("COLD PATH: выброшен непроверяемый пункт (%s): %s"
              % (why, line.strip()[:100]), file=sys.stderr)

    sys.stdout.write("\n".join(kept))
    if kept:
        sys.stdout.write("\n")


if __name__ == "__main__":
    main()
